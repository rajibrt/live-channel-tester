// Restore rows from a backup made by backup-activity-events.mjs.
//
// Usage (from vercel/):
//   node --env-file=.env.local scripts/restore-activity-events.mjs <backup.ndjson.gz> [--before=ISO] [--after=ISO] [--apply]
//
// Without --apply it is a dry run: it only reads the file and reports what
// would be inserted. With --apply it inserts rows whose created_at is in the
// chosen window and that are not already present (matched by created_at +
// user_id + event_type), then lowers client_activity_event_archive_totals by
// the restored counts so all-time dashboard totals are not double counted.
// Restored rows get new ids (the id column is generated by Postgres).
import { createClient } from "@supabase/supabase-js";
import { createReadStream } from "node:fs";
import { createGunzip } from "node:zlib";
import readline from "node:readline";

const args = process.argv.slice(2);
const file = args.find((a) => !a.startsWith("--"));
const opt = (name) => args.find((a) => a.startsWith(`--${name}=`))?.split("=").slice(1).join("=") || "";
const apply = args.includes("--apply");
const before = opt("before");
const after = opt("after");
if (!file) {
  console.error("Usage: restore-activity-events.mjs <backup.ndjson.gz> [--before=ISO] [--after=ISO] [--apply]");
  process.exit(1);
}

const admin = createClient(process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false } });

async function existingKeys(rows) {
  const times = rows.map((r) => r.created_at);
  const { data, error } = await admin
    .from("client_activity_events")
    .select("user_id,event_type,created_at")
    .in("created_at", times);
  if (error) throw new Error(error.message);
  return new Set((data || []).map((r) => `${r.user_id}|${r.event_type}|${new Date(r.created_at).toISOString()}`));
}

async function insertBatch(rows, stats) {
  if (!rows.length) return;
  const present = await existingKeys(rows);
  const fresh = rows.filter((r) => !present.has(`${r.user_id}|${r.event_type}|${new Date(r.created_at).toISOString()}`));
  stats.skippedExisting += rows.length - fresh.length;
  if (!fresh.length) return;
  const payload = fresh.map(({ user_id, event_type, event_data, created_at }) => ({ user_id, event_type, event_data, created_at }));
  const { error } = await admin.from("client_activity_events").insert(payload);
  if (!error) {
    for (const r of fresh) stats.restoredByType[r.event_type] = (stats.restoredByType[r.event_type] || 0) + 1;
    stats.restored += fresh.length;
    return;
  }
  // Fall back row by row (e.g. a client user that no longer exists).
  for (const row of payload) {
    const { error: rowError } = await admin.from("client_activity_events").insert(row);
    if (rowError) stats.failed += 1;
    else {
      stats.restored += 1;
      stats.restoredByType[row.event_type] = (stats.restoredByType[row.event_type] || 0) + 1;
    }
  }
}

const stats = { read: 0, selected: 0, restored: 0, skippedExisting: 0, failed: 0, restoredByType: {}, selectedByType: {} };
const rl = readline.createInterface({ input: createReadStream(file).pipe(createGunzip()), crlfDelay: Infinity });
let batch = [];
for await (const line of rl) {
  if (!line.trim()) continue;
  const row = JSON.parse(line);
  stats.read += 1;
  if (before && !(row.created_at < before)) continue;
  if (after && !(row.created_at >= after)) continue;
  stats.selected += 1;
  stats.selectedByType[row.event_type] = (stats.selectedByType[row.event_type] || 0) + 1;
  if (!apply) continue;
  batch.push(row);
  if (batch.length >= 200) {
    await insertBatch(batch, stats);
    batch = [];
    if (stats.selected % 20000 < 200) console.log(`restored ${stats.restored}, skipped ${stats.skippedExisting}, failed ${stats.failed}`);
  }
}
if (apply) await insertBatch(batch, stats);

if (apply && stats.restored) {
  const { data } = await admin.from("client_activity_event_archive_totals").select("event_type,archived_count");
  for (const row of data || []) {
    const minus = stats.restoredByType[row.event_type] || 0;
    if (!minus) continue;
    await admin
      .from("client_activity_event_archive_totals")
      .update({ archived_count: Math.max(0, Number(row.archived_count) - minus), updated_at: new Date().toISOString() })
      .eq("event_type", row.event_type);
  }
}

console.log(apply ? "RESTORE DONE" : "DRY RUN (nothing written; add --apply to restore)");
console.log(JSON.stringify(stats, null, 2));
